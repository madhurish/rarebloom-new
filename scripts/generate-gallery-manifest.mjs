// Scans public/gallery/*/ and writes the real filenames into
// src/data/galleryImages.ts. Run after adding or removing photos:
//
//     npm run gallery:manifest
//
// Only the image manifest is generated. Category names, descriptions and
// covers stay hand-authored in src/data/galleryData.ts and are never touched.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const galleryDir = path.join(root, "public", "gallery");
const outputFile = path.join(root, "src", "data", "galleryImages.ts");

const IMAGE_EXTS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

// "Bonsai 2.jpg" must sort before "Bonsai 10.jpg".
const natural = (a, b) => a.localeCompare(b, "en", { numeric: true, sensitivity: "base" });

const folders = fs
    .readdirSync(galleryDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort(natural);

const manifest = {};

for (const folder of folders) {
    const files = fs
        .readdirSync(path.join(galleryDir, folder))
        .filter((file) => !file.startsWith(".") && IMAGE_EXTS.has(path.extname(file).toLowerCase()))
        .sort(natural);

    manifest[folder] = files.map((file) => ({
        name: path.basename(file, path.extname(file)),
        path: `/gallery/${folder}/${file}`,
    }));
}

const body = `// AUTO-GENERATED by scripts/generate-gallery-manifest.mjs — do not edit by hand.
// Regenerate with: npm run gallery:manifest

import type { GalleryData } from "./galleryData";

export const galleryImages: GalleryData = ${JSON.stringify(manifest, null, 4)};
`;

fs.writeFileSync(outputFile, body);

console.log(`Wrote ${path.relative(root, outputFile)}`);
for (const folder of folders) {
    console.log(`  ${folder}: ${manifest[folder].length} images`);
}
